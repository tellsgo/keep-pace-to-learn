"""Gradient check: OTA exact backward equals PyTorch autograd of satH^T; smoke forward/backward on random data."""
import sys, pathlib, torch, math
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import run
torch.manual_seed(0)
dev = 'cuda'
H = torch.randn(8, 4, dtype=torch.complex64, device=dev)
s = torch.randn(5, 8, 4, dtype=torch.complex64, device=dev, requires_grad=True)
W = torch.randn(5, 8, 8, dtype=torch.complex64, device=dev)
y = s.__matmul__(H.transpose(0, 1))
L = (y * W).real.sum() + (y.abs() ** 2).sum()
(g1,) = torch.autograd.grad(L, s)
s2 = s.detach().clone().requires_grad_(True)
y2 = run.OTA.apply(s2, H, H, torch.zeros(5, 8, 4, dtype=torch.complex64, device=dev), False)
L2 = (y2 * W).real.sum() + (y2.abs() ** 2).sum()
(g2,) = torch.autograd.grad(L2, s2)
print('exact backward max err', (g1 - g2).abs().max().item())
y3 = run.OTA.apply(s.detach().clone().requires_grad_(True), H, H, torch.zeros(5, 8, 4, dtype=torch.complex64, device=dev), True)
ch = run.Channel(710172100, dev)
Hf = ch.H(torch.zeros(460, device=dev, dtype=torch.float64), 0.0)
print('H power', (Hf.abs() ** 2).mean().item())
dv = run.Device().to(dev)
rx = run.Receiver().to(dev)
x = torch.randn(16, 3, 32, 32, device=dev)
sv = dv(x)
print('power per sample', (sv.abs() ** 2).flatten(1).sum(1)[:3].tolist())
yy = run.OTA.apply(sv, Hf, ch.H(torch.zeros(460, device=dev, dtype=torch.float64), 0.3), torch.zeros(16, 8, 4, dtype=torch.complex64, device=dev), True)
loss = torch.nn.functional.cross_entropy(rx(run.mmse(Hf, yy, 0.01)), torch.randint(0, 10, (16,), device=dev))
loss.backward()
print('smoke ok', loss.item())
